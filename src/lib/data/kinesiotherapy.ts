export type ExercisePhase = "warmup" | "main" | "cooldown";

export interface KinExercise {
  id: string;
  title: string;
  phase: ExercisePhase;
  /** На что направлено упражнение. */
  purpose: string;
  /** Как выполняется. */
  how: string;
  /** Реплика взрослого (прямая речь). */
  cue?: string;
  easier?: string;
  harder?: string;
  /** Дозировка. */
  dose: string;
}

export interface KinSession {
  /** Глобальный номер занятия 1..12. */
  number: number;
  week: number;
  title: string;
  intro: string;
  exercises: KinExercise[];
}

export interface KinWeek {
  number: number;
  phase: 1 | 2;
  title: string;
  summary: string;
  /** Номера занятий этой недели. */
  sessions: number[];
  /** Пояснение к неделям, где занятия собираются из ротации упражнений. */
  note?: string;
}

export interface KinQuestion {
  n: number;
  title: string;
  text: string;
}

export interface KinRedFlag {
  category: string;
  signs: string;
}

export interface KinScaleLevel {
  score: 0 | 1 | 2;
  text: string;
}

export interface KinCriterion {
  title: string;
  text: string;
}

export interface KinEquipment {
  pro: string;
  home: string;
  purpose: string;
}

